#!/usr/bin/env python3
"""
創建一個簡單的 I2C 掃描 MAVLink 腳本
用於診斷 I2C 設備是否存在
"""

print("""
════════════════════════════════════════════════════════════════════════
              I2C 診斷和 RangeFinder 參數檢查指南
════════════════════════════════════════════════════════════════════════

【第一步：確認參數設置】
────────────────────────────────────────────────────────────────────────
在 Mission Planner 中，前往：Config → Full Parameter List

搜索並設置以下參數：

  RNGFND1_TYPE     = 45      ⚠️ 必須是 45（不是 32！）
  RNGFND1_ADDR     = 65      (0x41 的十進制)
  RNGFND1_ORIENT   = 25      (Down 朝下)
  RNGFND1_MIN_CM   = 30
  RNGFND1_MAX_CM   = 1500
  
設置後，點擊 "Write Params"，然後 **重啟飛控**！

【第二步：使用 MAVProxy 驗證參數】
────────────────────────────────────────────────────────────────────────
# 連接飛控
mavproxy.py --master=/dev/ttyACM0  # Linux
# 或
mavproxy.py --master=COM3          # Windows

# 在 MAVProxy 中執行：
param show RNGFND1*

# 應該看到：
# RNGFND1_TYPE = 45.000000
# RNGFND1_ADDR = 65.000000
# ...

【第三步：檢查啟動訊息】
────────────────────────────────────────────────────────────────────────
在 MAVProxy 中，重啟飛控後應該看到：

  MN68820: detect() called
  MN68820: I2C device OK, creating sensor object
  ...

如果看到 "MN68820: I2C device is null in detect()"
  → hwdef 配置問題，需要檢查 RANGEFINDER 行

如果完全沒有 MN68820 訊息
  → RNGFND1_TYPE 沒有設置為 45

【第四步：手動 I2C 掃描（進階）】
────────────────────────────────────────────────────────────────────────
如果需要確認 MN68820 是否在 I2C 總線上：

1. 在 hwdef.dat 中臨時添加：
   define AP_PERIPH_I2C_SCANNER_ENABLED 1

2. 重新編譯並上傳

3. 在 MAVProxy 中執行：
   i2cscan

這會掃描 I2C 總線上的所有設備。MN68820 應該出現在地址 0x41。

【第五步：檢查硬體連接】
────────────────────────────────────────────────────────────────────────
物理檢查清單：
  □ MN68820 VCC 連接到飛控 3.3V 或 5V（確認感測器規格）
  □ MN68820 GND 連接到飛控 GND
  □ MN68820 SCL 連接到飛控 PB8
  □ MN68820 SDA 連接到飛控 PB9
  □ I2C 總線有 4.7K 上拉電阻到 VCC（某些模組內建）

使用萬用表確認：
  - 電源電壓正確（3.3V 或 5V）
  - SCL/SDA 線路沒有短路
  - GND 連接良好

════════════════════════════════════════════════════════════════════════
""")

